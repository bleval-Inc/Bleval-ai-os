class ResearchReport(ResearchBase):
    """Research report generated by Nova/Atlas."""

    __tablename__ = "research_reports"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    uuid: Mapped[str] = mapped_column(String(36), unique=True, nullable=False, index=True)

    # Identity
    title: Mapped[str] = mapped_column(String(500), nullable=False, index=True)
    slug: Mapped[str] = mapped_column(String(500), unique=True, nullable=False, index=True)
    description: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Content
    executive_summary: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    content: Mapped[Optional[str]] = mapped_column(Text, nullable=True)  # Markdown
    content_html: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    methodology: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    findings: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)
    recommendations: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)

    # Metadata
    status: Mapped[ResearchStatus] = mapped_column(
        SQLEnum(ResearchStatus), default=ResearchStatus.PLANNED, nullable=False, index=True
    )
    topic: Mapped[Optional[str]] = mapped_column(String(255), nullable=True, index=True)
    industry: Mapped[Optional[str]] = mapped_column(String(100), nullable=True, index=True)
    keywords: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)
    tags: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)

    # Attribution
    author_agent: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)  # nova, atlas
    reviewer_agent: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    approved_by: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)

    # Sources
    sources: Mapped[List[dict]] = mapped_column(JSON, default=list, nullable=False)  # [{title, url, type, credibility}]
    source_urls: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)

    # Metrics
    word_count: Mapped[int] = mapped_column(Integer, default=0)
    reading_time_minutes: Mapped[int] = mapped_column(Integer, default=0)
    credibility_score: Mapped[Optional[Decimal]] = mapped_column(Numeric(3, 2), nullable=True)  # 0-1

    # Dates
    research_started_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)
    research_completed_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)
    published_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True, index=True)

    # Timestamps
    created_at: Mapped[datetime] = mapped_column(DateTime, default=func.now(), nullable=False)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, default=func.now(), onupdate=func.now(), nullable=False
    )

    # Relationships
    content_pieces: Mapped[List["ContentPiece"]] = relationship(
        "ContentPiece", back_populates="research_report", lazy="selectin"
    )

    __table_args__ = (
        Index("ix_research_reports_status_topic", "status", "topic"),
        Index("ix_research_reports_author_status", "author_agent", "status"),
    )

    def __repr__(self) -> str:
        return f"<ResearchReport(id={self.id}, title={self.title[:50]}, status={self.status.value})>"



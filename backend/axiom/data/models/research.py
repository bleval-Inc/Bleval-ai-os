class WebPage(ResearchBase):
    """Crawled/scraped web page."""

    __tablename__ = "web_pages"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    uuid: Mapped[str] = mapped_column(String(36), unique=True, nullable=False, index=True)

    # Identity
    url: Mapped[str] = mapped_column(String(1000), unique=True, nullable=False, index=True)
    canonical_url: Mapped[Optional[str]] = mapped_column(String(1000), nullable=True)
    title: Mapped[Optional[str]] = mapped_column(String(500), nullable=True)
    domain: Mapped[str] = mapped_column(String(255), nullable=False, index=True)

    # Content
    content: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    content_html: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    markdown: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Metadata
    meta_description: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    meta_keywords: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)
    og_tags: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    structured_data: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)  # JSON-LD

    # Classification
    page_type: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)  # article, product, landing, etc.
    categories: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)
    tags: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)

    # Content analysis
    word_count: Mapped[int] = mapped_column(Integer, default=0)
    readability_score: Mapped[Optional[Decimal]] = mapped_column(Numeric(5, 2), nullable=True)
    sentiment: Mapped[Optional[Sentiment]] = mapped_column(SQLEnum(Sentiment), nullable=True)
    sentiment_score: Mapped[Optional[Decimal]] = mapped_column(Numeric(3, 2), nullable=True)
    entities: Mapped[List[dict]] = mapped_column(JSON, default=list, nullable=False)

    # Links
    internal_links: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)
    external_links: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)

    # Crawler metadata
    status_code: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    content_type: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    content_length: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    response_headers: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)

    # Processing
    is_indexed: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    is_processed: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    processing_error: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Dates
    last_crawled_at: Mapped[datetime] = mapped_column(DateTime, default=func.now(), nullable=False, index=True)
    last_modified_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)

    # Timestamps
    created_at: Mapped[datetime] = mapped_column(DateTime, default=func.now(), nullable=False)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, default=func.now(), onupdate=func.now(), nullable=False
    )

    __table_args__ = (
        Index("ix_web_pages_domain_crawled", "domain", "last_crawled_at"),
        Index("ix_web_pages_type_indexed", "page_type", "is_indexed"),
    )

    def __repr__(self) -> str:
        return f"<WebPage(url={self.url[:80]}, domain={self.domain})>"



class KnowledgeEntry(ResearchBase):
    """Knowledge base entry - curated, searchable knowledge."""

    __tablename__ = "knowledge_entries"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    uuid: Mapped[str] = mapped_column(String(36), unique=True, nullable=False, index=True)

    # Identity
    title: Mapped[str] = mapped_column(String(500), nullable=False, index=True)
    slug: Mapped[str] = mapped_column(String(500), unique=True, nullable=False, index=True)

    # Content
    content: Mapped[str] = mapped_column(Text, nullable=False)  # Markdown
    content_html: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    summary: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Classification
    category: Mapped[Optional[str]] = mapped_column(String(100), nullable=True, index=True)
    subcategory: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    tags: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)
    keywords: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)

    # Versioning
    version: Mapped[int] = mapped_column(Integer, default=1, nullable=False)
    previous_version_id: Mapped[Optional[int]] = mapped_column(
        BigInteger, ForeignKey("knowledge_entries.id"), nullable=True
    )

    # Quality
    is_verified: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    verified_by: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    verified_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)
    credibility_score: Mapped[Optional[Decimal]] = mapped_column(Numeric(3, 2), nullable=True)

    # Usage
    view_count: Mapped[int] = mapped_column(Integer, default=0)
    helpful_count: Mapped[int] = mapped_column(Integer, default=0)
    not_helpful_count: Mapped[int] = mapped_column(Integer, default=0)

    # Ownership
    owner_id: Mapped[Optional[str]] = mapped_column(String(100), nullable=True, index=True)

    # Timestamps
    created_at: Mapped[datetime] = mapped_column(DateTime, default=func.now(), nullable=False)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, default=func.now(), onupdate=func.now(), nullable=False
    )
    published_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True, index=True)

    # Self-referential relationship
    previous_version: Mapped[Optional["KnowledgeEntry"]] = relationship(
        "KnowledgeEntry", remote_side=[id], backref="next_version"
    )

    __table_args__ = (
        Index("ix_knowledge_entries_category_verified", "category", "is_verified"),
        Index("ix_knowledge_entries_owner", "owner_id"),
    )

    def __repr__(self) -> str:
        return f"<KnowledgeEntry(id={self.id}, title={self.title[:50]}, category={self.category})>"
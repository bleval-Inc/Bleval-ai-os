class ContentPiece(ResearchBase):
    """Content piece for marketing/sales."""

    __tablename__ = "content_pieces"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    uuid: Mapped[str] = mapped_column(String(36), unique=True, nullable=False, index=True)

    # Identity
    title: Mapped[str] = mapped_column(String(500), nullable=False, index=True)
    slug: Mapped[str] = mapped_column(String(500), unique=True, nullable=False, index=True)
    content_type: Mapped[ContentType] = mapped_column(SQLEnum(ContentType), nullable=False, index=True)

    # Content
    outline: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    content: Mapped[Optional[str]] = mapped_column(Text, nullable=True)  # Markdown
    content_html: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # SEO
    meta_title: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    meta_description: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    focus_keyword: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    keywords: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)

    # Status
    status: Mapped[ContentStatus] = mapped_column(
        SQLEnum(ContentStatus), default=ContentStatus.IDEA, nullable=False, index=True
    )

    # Attribution
    research_report_id: Mapped[Optional[int]] = mapped_column(
        BigInteger, ForeignKey("research_reports.id"), nullable=True
    )
    author_agent: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)  # creator
    reviewer_agent: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    approved_by: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)

    # Distribution
    distribution_channels: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)
    published_urls: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)

    # Metrics
    views: Mapped[int] = mapped_column(Integer, default=0)
    clicks: Mapped[int] = mapped_column(Integer, default=0)
    conversions: Mapped[int] = mapped_column(Integer, default=0)
    engagement_score: Mapped[Optional[Decimal]] = mapped_column(Numeric(5, 2), nullable=True)

    # Dates
    draft_completed_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)
    reviewed_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)
    approved_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)
    published_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True, index=True)

    # Timestamps
    created_at: Mapped[datetime] = mapped_column(DateTime, default=func.now(), nullable=False)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, default=func.now(), onupdate=func.now(), nullable=False
    )

    # Relationships
    research_report: Mapped[Optional["ResearchReport"]] = relationship("ResearchReport", back_populates="content_pieces")

    __table_args__ = (
        Index("ix_content_pieces_type_status", "content_type", "status"),
        Index("ix_content_pieces_published", "published_at"),
    )

    def __repr__(self) -> str:
        return f"<ContentPiece(id={self.id}, title={self.title[:50]}, type={self.content_type.value})>"



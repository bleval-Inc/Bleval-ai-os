"""RESEARCH Domain Models — Web Research, News, Content, Knowledge Base."""

import enum
from datetime import datetime
from decimal import Decimal
from typing import Optional, List

from sqlalchemy import (
    BigInteger,
    Boolean,
    DateTime,
    Enum as SQLEnum,
    ForeignKey,
    Index,
    Integer,
    MetaData,
    Numeric,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.sqlite import JSON
from sqlalchemy.orm import Mapped, mapped_column, relationship

from axiom.data.database import DeclarativeBase


class ResearchBase(DeclarativeBase):
    """Base for RESEARCH domain models."""
    metadata = MetaData(schema="research")


class ResearchStatus(str, enum.Enum):
    """Research report status."""

    PLANNED = "planned"
    IN_PROGRESS = "in_progress"
    REVIEW = "review"
    COMPLETED = "completed"
    PUBLISHED = "published"
    ARCHIVED = "archived"


class ContentType(str, enum.Enum):
    """Content piece types."""

    BLOG_POST = "blog_post"
    ARTICLE = "article"
    WHITEPAPER = "whitepaper"
    CASE_STUDY = "case_study"
    NEWSLETTER = "newsletter"
    SOCIAL_POST = "social_post"
    VIDEO_SCRIPT = "video_script"
    EMAIL_SEQUENCE = "email_sequence"
    LANDING_PAGE = "landing_page"
    REPORT = "report"


class ContentStatus(str, enum.Enum):
    """Content status."""

    IDEA = "idea"
    OUTLINE = "outline"
    DRAFTING = "drafting"
    REVIEW = "review"
    APPROVED = "approved"
    PUBLISHED = "published"
    ARCHIVED = "archived"


class NewsSource(str, enum.Enum):
    """News source categories."""

    RSS = "rss"
    API = "api"
    SCRAPED = "scraped"
    MANUAL = "manual"
    WEBHOOK = "webhook"


class Sentiment(str, enum.Enum):
    """Sentiment analysis."""

    POSITIVE = "positive"
    NEGATIVE = "negative"
    NEUTRAL = "neutral"



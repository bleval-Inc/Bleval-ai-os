class NewsArticle(ResearchBase):
    """News article from feeds, APIs, or scraping."""

    __tablename__ = "news_articles"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    uuid: Mapped[str] = mapped_column(String(36), unique=True, nullable=False, index=True)

    # Identity
    title: Mapped[str] = mapped_column(String(500), nullable=False, index=True)
    url: Mapped[str] = mapped_column(String(1000), unique=True, nullable=False, index=True)
    canonical_url: Mapped[Optional[str]] = mapped_column(String(1000), nullable=True)

    # Content
    summary: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    content: Mapped[Optional[str]] = mapped_column(Text, nullable=True)  # Full text
    content_html: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Author & publication
    author: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    publication: Mapped[Optional[str]] = mapped_column(String(255), nullable=True, index=True)
    publication_domain: Mapped[Optional[str]] = mapped_column(String(255), nullable=True, index=True)

    # Classification
    categories: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)
    tags: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)
    keywords: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)
    entities: Mapped[List[dict]] = mapped_column(JSON, default=list, nullable=False)  # Named entities

    # Sentiment
    sentiment: Mapped[Optional[Sentiment]] = mapped_column(SQLEnum(Sentiment), nullable=True, index=True)
    sentiment_score: Mapped[Optional[Decimal]] = mapped_column(Numeric(3, 2), nullable=True)  # -1 to 1

    # Source
    source_type: Mapped[NewsSource] = mapped_column(SQLEnum(NewsSource), nullable=False)
    source_id: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)  # Feed ID, etc.

    # Media
    image_url: Mapped[Optional[str]] = mapped_column(String(1000), nullable=True)
    video_url: Mapped[Optional[str]] = mapped_column(String(1000), nullable=True)

    # Dates
    published_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True, index=True)
    fetched_at: Mapped[datetime] = mapped_column(DateTime, default=func.now(), nullable=False, index=True)

    # Timestamps
    created_at: Mapped[datetime] = mapped_column(DateTime, default=func.now(), nullable=False)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, default=func.now(), onupdate=func.now(), nullable=False
    )

    # Metadata
    language: Mapped[str] = mapped_column(String(10), default="en", nullable=False)
    word_count: Mapped[int] = mapped_column(Integer, default=0)
    credibility_score: Mapped[Optional[Decimal]] = mapped_column(Numeric(3, 2), nullable=True)
    is_processed: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False, index=True)

    __table_args__ = (
        Index("ix_news_articles_published_source", "published_at", "source_type"),
        Index("ix_news_articles_sentiment_published", "sentiment", "published_at"),
        Index("ix_news_articles_domain_published", "publication_domain", "published_at"),
    )

    def __repr__(self) -> str:
        return f"<NewsArticle(id={self.id}, title={self.title[:50]}, source={self.source_type.value})>"


